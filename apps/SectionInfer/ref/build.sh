#!/bin/bash
# Build the C++ reference for SectionInfer from the ORIGINAL beatmapper
# complete_algo.cpp.  The whole file drags in the chord model, subprocesses,
# onset detection etc., so the section-inference core is extracted verbatim
# (by marker lines) into gen_sections.inc:
#   - fmt_time .. nearest_beat, overlap_len   (beat-map helpers)
#   - struct BeatFeatures .. infer_sections   (the section-inference core)
# The only edit: two counters (DP states relaxed, best final DP score) are
# inserted into partition_span so its DP is compared with the Virgil port.
# Usage: ref/build.sh && ref/sectioninfer_ref <reps>
set -e
HERE=$(cd $(dirname "${BASH_SOURCE[0]}") && pwd)
BM_SRC=${BM_SRC:-$HOME/RiffHound/RiffHound/beatmapper/src}
SRC=$BM_SRC/complete_algo.cpp
OUT=$HERE/gen_sections.inc
{
  echo "// GENERATED by build.sh from $SRC -- do not edit"
  awk '/^static void fmt_time/{f=1} /^bool complete_cand_in_range/{f=0} f' $SRC
  awk '/^static double overlap_len/{f=1} f{print} f&&/^}/{exit}' $SRC
  awk '/^struct BeatFeatures/{f=1} /^\/\/ Chord inference/{f=0} f' $SRC \
    | sed -e 's/^\( *\)if (d < -1e17) continue;$/\1if (d < -1e17) continue; g_dpCells++;/' \
          -e 's/^\( *\)if (best < -1e17) return;$/\1if (best < -1e17) return; g_dpBest += best;/'
} > $OUT
grep -q g_dpCells $OUT && grep -q g_dpBest $OUT
c++ -O2 -std=c++17 -ffp-contract=off -w -I"$BM_SRC" -o "$HERE/sectioninfer_ref" "$HERE/main.cpp"
